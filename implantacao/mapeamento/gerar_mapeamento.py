def validar():
    campos = {(e, c) for e, lst in CANONICO.items() for c, _, _ in lst}
    erros = [f"{o}.{t}.{col}: {e}.{c} não existe no CANONICO"
             for o, e, c, t, col, _, _ in DE_PARA if (e, c) not in campos]
    vistos = set()
    for o, e, c, *_ in DE_PARA:
        if (o, e, c) in vistos:
            erros.append(f"{o}: {e}.{c} mapeado duas vezes")
        vistos.add((o, e, c))
    if erros:
        raise SystemExit("\n".join(erros))

if __name__ == "__main__":
    validar()
    with (AQUI / "dicionario_canonico.csv").open("w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f, delimiter=";")
        w.writerow(["entidade", "campo", "tipo", "descricao"])
        w.writerows((e, c, t, d) for e, lst in CANONICO.items() for c, t, d in lst)
